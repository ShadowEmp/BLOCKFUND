const { DataTypes } = require('sequelize');
const sequelize = require('./index');
const User = require('./User');

const Campaign = sequelize.define('Campaign', {
  id: {
    type: DataTypes.UUID,
    defaultValue: DataTypes.UUIDV4,
    primaryKey: true,
  },
  title: {
    type: DataTypes.STRING,
    allowNull: false,
  },
  description: {
    type: DataTypes.TEXT,
    allowNull: false,
  },
  goal: {
    type: DataTypes.DECIMAL(20, 8), // For MATIC amounts
    allowNull: false,
  },
  deadline: {
    type: DataTypes.DATE,
    allowNull: false,
  },
  ipfs_hash: {
    type: DataTypes.STRING, // CID from Pinata
  },
  contract_campaign_id: {
    type: DataTypes.INTEGER, // Maps to the ID generated by the smart contract
  },
  contract_address: {
    type: DataTypes.STRING,
  },
  creator_wallet: {
    type: DataTypes.STRING,
    allowNull: false,
  },
}, {
  timestamps: true,
  createdAt: 'created_at',
  updatedAt: 'updated_at',
});

Campaign.belongsTo(User, { foreignKey: 'creator_wallet', targetKey: 'wallet_address', as: 'Creator' });

module.exports = Campaign;
